import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { apply, ROUTES as R } from "../index.js";
const routes=new Map();
const root = await mkdtemp(join(tmpdir(), "gzs-typo-"));
apply({ logger:{info(){},warn(){}}, effect(){}, provide(){}, connection:{ fetch:{ register:(s)=>{routes.set(s.path,s); return ()=>{};} } } }, { root });
const get=(p,q="")=>routes.get(p).fetch({url:`http://x${p}${q}`,headers:new Headers()});
const post=(p,b)=>routes.get(p).fetch({url:`http://x${p}`,json:async()=>b});
const r = await post(R.create,{title:"拼错的类型", track:"mother-baby", sections:1});
console.log("create 状态码:", r.status);
const s = await (await get(R.state)).json();
console.log("这篇的 track:", s.articles[0]?.track);
console.log("byTrack:", JSON.stringify(s.counts.byTrack));
const chips = s.tracks.map(t=>t.id);
console.log("筛选项里有 mother-baby 吗:", chips.includes("mother-baby"));
const filtered = await (await get(R.state, "?track=mother-baby")).json();
console.log("按该 id 筛回来几篇:", filtered.articles.length, "(0 表示永远筛不到)");
await rm(root,{recursive:true,force:true});
